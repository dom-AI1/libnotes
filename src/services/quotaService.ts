import { supabase, isSupabaseConfigured } from './supabaseClient';
import type { ExportStyleMode } from './pdfExportService';

const STORAGE_KEY_DAILY_PDF_QUOTA = 'libnotes_pdf_quota_v1';

export interface QuotaCheckResult {
  allowed: boolean;
  isRedownload: boolean;
  remainingGenerations: number;
  message: string;
  resetAtUtc?: string;
}

interface StoredQuotaRecord {
  utcDate: string; // YYYY-MM-DD
  userId: string;
  generatedKitModes: string[]; // array of "kitId:mode"
  count: number;
}

/**
 * Returns the current date formatted as UTC YYYY-MM-DD
 */
export function getCurrentUtcDateString(): string {
  const now = new Date();
  return now.toISOString().split('T')[0];
}

/**
 * Calculates ISO timestamp for the next UTC midnight reset
 */
export function getNextUtcMidnightIso(): string {
  const now = new Date();
  const tomorrowUtc = new Date(Date.UTC(
    now.getUTCFullYear(),
    now.getUTCMonth(),
    now.getUTCDate() + 1,
    0, 0, 0, 0
  ));
  return tomorrowUtc.toISOString();
}

/**
 * In-memory concurrency lock to prevent duplicate clicks and race conditions
 */
const pendingQuotaRequests = new Set<string>();

/**
 * Checks and atomically consumes PDF generation quota for a user.
 * Policy:
 * 1. Exactly 1 NEW PDF generation per user per UTC calendar day on Free Plan.
 * 2. Existing PDFs can be re-downloaded unlimited times without consuming quota.
 * 3. Failed generations do not consume quota.
 * 4. Concurrent duplicate requests are rejected via mutex lock.
 */
export async function checkAndConsumePdfQuota(
  userId: string | null | undefined,
  kitId: string,
  exportMode: ExportStyleMode = 'all'
): Promise<QuotaCheckResult> {
  const effectiveUserId = userId || 'anonymous_guest';
  const targetKey = `${kitId}:${exportMode}`;
  const lockKey = `${effectiveUserId}:${targetKey}`;

  // Concurrency guard: reject simultaneous in-flight clicks
  if (pendingQuotaRequests.has(lockKey)) {
    return {
      allowed: false,
      isRedownload: false,
      remainingGenerations: 0,
      message: 'A PDF export request is already in progress. Please wait a moment.',
    };
  }

  pendingQuotaRequests.add(lockKey);

  try {
    const todayUtc = getCurrentUtcDateString();
    const nextResetUtc = getNextUtcMidnightIso();

    // 1. Try Supabase Atomic Check & Consume if configured and user is authenticated
    if (isSupabaseConfigured() && userId && userId !== 'anonymous_guest') {
      try {
        const { data, error } = await supabase.rpc('check_and_consume_pdf_quota', {
          p_user_id: userId,
          p_kit_id: kitId,
          p_export_mode: exportMode,
        });

        if (!error && data) {
          return {
            allowed: Boolean(data.allowed),
            isRedownload: Boolean(data.is_redownload),
            remainingGenerations: Number(data.remaining_generations ?? (data.allowed ? 0 : 0)),
            message: data.message || (data.allowed ? 'PDF export approved.' : 'Daily PDF quota reached.'),
            resetAtUtc: data.reset_at_utc || nextResetUtc,
          };
        }
      } catch (rpcErr) {
        console.warn('[Libnotes Quota] Supabase RPC deferred or table missing, falling back to client-safe persistence:', rpcErr);
      }
    }

    // 2. Client-safe persistent quota tracking (localStorage with UTC date boundary)
    const raw = localStorage.getItem(`${STORAGE_KEY_DAILY_PDF_QUOTA}_${effectiveUserId}`);
    let record: StoredQuotaRecord = {
      utcDate: todayUtc,
      userId: effectiveUserId,
      generatedKitModes: [],
      count: 0,
    };

    if (raw) {
      try {
        const parsed: StoredQuotaRecord = JSON.parse(raw);
        if (parsed.utcDate === todayUtc) {
          record = parsed;
        } else {
          // New UTC day: reset count and keep history of generated keys for free re-downloads
          record = {
            utcDate: todayUtc,
            userId: effectiveUserId,
            generatedKitModes: parsed.generatedKitModes || [],
            count: 0,
          };
        }
      } catch {
        // Corrupt local record, use fresh structure
      }
    }

    // Check if this exact PDF was previously generated by this user (Free Re-download Rule)
    const isExistingPdf = record.generatedKitModes.includes(targetKey);
    if (isExistingPdf) {
      return {
        allowed: true,
        isRedownload: true,
        remainingGenerations: Math.max(0, 1 - record.count),
        message: 'Re-downloading your previously generated PDF (Free Plan quota preserved).',
        resetAtUtc: nextResetUtc,
      };
    }

    // New generation: check if daily limit (1 per UTC day) has already been reached
    if (record.count >= 1) {
      return {
        allowed: false,
        isRedownload: false,
        remainingGenerations: 0,
        message: 'Free Plan Daily Limit Reached: You have used your 1 new PDF generation for today (UTC). You can still re-download any previously generated notes at any time!',
        resetAtUtc: nextResetUtc,
      };
    }

    // Consume 1 quota count and record generated kit key
    record.count += 1;
    if (!record.generatedKitModes.includes(targetKey)) {
      record.generatedKitModes.push(targetKey);
    }
    localStorage.setItem(`${STORAGE_KEY_DAILY_PDF_QUOTA}_${effectiveUserId}`, JSON.stringify(record));

    return {
      allowed: true,
      isRedownload: false,
      remainingGenerations: 0,
      message: 'New PDF generation approved under Free Plan (1/1 used for today).',
      resetAtUtc: nextResetUtc,
    };
  } finally {
    pendingQuotaRequests.delete(lockKey);
  }
}

/**
 * Check remaining quota without consuming it (for UI displays)
 */
export function getRemainingDailyPdfQuota(userId: string | null | undefined): {
  remaining: number;
  resetAtUtc: string;
} {
  const effectiveUserId = userId || 'anonymous_guest';
  const todayUtc = getCurrentUtcDateString();
  const nextResetUtc = getNextUtcMidnightIso();

  const raw = localStorage.getItem(`${STORAGE_KEY_DAILY_PDF_QUOTA}_${effectiveUserId}`);
  if (!raw) {
    return { remaining: 1, resetAtUtc: nextResetUtc };
  }

  try {
    const record: StoredQuotaRecord = JSON.parse(raw);
    if (record.utcDate !== todayUtc) {
      return { remaining: 1, resetAtUtc: nextResetUtc };
    }
    return {
      remaining: Math.max(0, 1 - (record.count || 0)),
      resetAtUtc: nextResetUtc,
    };
  } catch {
    return { remaining: 1, resetAtUtc: nextResetUtc };
  }
}

